package rulesinvariables;

public class Student {

        public static void main(String[] args) {

            // Variable names should start with lowercase letters
            int id = 101;

            // If variable name has two words,
            // first word starts with lowercase
            // second word starts with uppercase
            // This is called camelCase
            String firstName = "Vaishnavi";

            // Another camelCase example
            String name  = "Putta";
            System.out.println(id);
            System.out.println(firstName);
            System.out.println(name);
        }
    }
