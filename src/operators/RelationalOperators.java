package operators;

public class RelationalOperators {
    public static void main(String[] args) {
        int i = 12;
        int j = 15;
        System.out.println(i==j);
        System.out.println(i!=j);
        System.out.println(i<j);
        System.out.println(i>j);
        System.out.println(i<=j);
        System.out.println(i>=j);
    }
}
