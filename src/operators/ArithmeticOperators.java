package operators;

public class ArithmeticOperators {
    public static void main(String[] args) {
        int i = 10;
        int j = 15;
        System.out.println(i+j);
        System.out.println(i-j);
        System.out.println(i*j);
        System.out.println(i/j);
        System.out.println(i%j);
    }
}
